import { FunctionDemo } from "@/components/function-demo";
import { Section } from "@/components/section";
import { data } from "@/lib/data";
import { highlight } from "@/lib/highlight";

/** Shiki's HTML split into one string per source line, so lines can be made clickable. */
function lines(html: string): string[] {
  const code = html.slice(html.indexOf("<code>") + 6, html.lastIndexOf("</code>"));
  return code.split("\n");
}

export async function DemoSection() {
  const demo = data.demo;
  const sources = Object.keys(demo.symbols);
  const highlighted: Record<string, string[]> = {};
  for (const file of sources) {
    highlighted[file] = lines(await highlight(demo.files[file], "python"));
  }
  return (
    <Section
      id="demo"
      eyebrow="Function-level selection"
      title={
        <>
          Change a function. See exactly which <span className="text-amber">test functions</span>{" "}
          run, and why.
        </>
      }
      intro={
        <>
          This is a small billing project and Karma&apos;s real output for it, generated by{" "}
          <code className="font-mono text-sm">scripts/build_demo.py</code>. Click any function,
          method or constant to change it. A <code className="font-mono text-sm">conftest.py</code>{" "}
          imports the invoice module, so file-level selection must run every test file; function
          level follows the names and runs only what can break.
        </>
      }
    >
      <FunctionDemo demo={demo} highlighted={highlighted} />
    </Section>
  );
}
